import {chromium} from 'playwright';
import {cp,mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';

const root=path.resolve(import.meta.dirname,'..'),extension=path.join(root,'.structured-image-extension');
await cp(path.join(root,'dist'),extension,{recursive:true});
const manifest=JSON.parse(await readFile(path.join(extension,'manifest.json'),'utf8'));
await writeFile(path.join(extension,'manifest.json'),JSON.stringify({...manifest,host_permissions:['http://127.0.0.1/*']}));
const targetHtml='<!doctype html><meta charset="utf-8"><title>独立目标表单</title><form id="target"><section><label for="name">名称</label><input id="name"></section><section><label for="priority">优先级</label><input id="priority" type="number"></section><article><div class="field-label"><label>匹配规则</label></div><div><input id="value" data-field="value" placeholder="请输入value"><input id="key" data-field="key" placeholder="请输入key"><label><input id="regex" type="checkbox">正则表达式</label></div></article><button type="submit">提交</button></form>';
const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html;charset=utf-8');res.end(targetHtml);});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let context;
try {
  context=await chromium.launchPersistentContext('',{executablePath:process.env.TEST_CHROMIUM,headless:true,viewport:{width:1200,height:850},args:[`--disable-extensions-except=${extension}`,`--load-extension=${extension}`]});
  const worker=context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const source=await context.newPage();
  await source.setContent('<!doctype html><meta charset="utf-8"><style>body{margin:0;padding:24px;font:18px "Microsoft YaHei",sans-serif;background:#fff}form{width:950px}section{display:flex;align-items:center;gap:18px;margin:28px 0}label{width:110px;text-align:right}input{font:18px "Microsoft YaHei",sans-serif;height:42px;box-sizing:border-box;border:1px solid #aaa;border-radius:3px;padding:8px;width:360px}section:not(:last-child) input{width:738px}</style><form><section><label>名称</label><input value="示例站点"></section><section><label>优先级</label><input value="20"></section><section><label>匹配规则</label><input value="severity"><input value="P[0-2]"></section></form>');
  await mkdir(path.join(root,'test-artifacts'),{recursive:true});
  const screenshot=path.join(root,'test-artifacts/structured-source.png');
  await source.locator('form').screenshot({path:screenshot});
  await source.close();
  const target=await context.newPage();await target.goto(`http://127.0.0.1:${server.address().port}/`);
  await target.evaluate(()=>{document.querySelector('form').onsubmit=event=>{event.preventDefault();globalThis.submitted=true;};});
  const panel=await context.newPage();await panel.setViewportSize({width:390,height:900});
  const remote=[],errors=[];
  context.on('request',request=>{if(/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:')) remote.push(request.url());});
  panel.on('pageerror',error=>errors.push(error.message));
  await panel.goto(`chrome-extension://${new URL(worker.url()).host}/panel.html`);
  await panel.waitForFunction(()=>!document.getElementById('choose').disabled);
  await context.setOffline(true);
  await panel.locator('#file').setInputFiles(screenshot);
  await panel.waitForFunction(()=>document.getElementById('cancel').hidden && document.querySelectorAll('.data-row').length>0,null,{timeout:120000});
  const saved=await panel.evaluate(async()=> (await chrome.storage.local.get('savedCapture')).savedCapture);
  assert.deepEqual(saved.sourceRows,[],'The test must have no source DOM evidence');
  assert.equal(saved.rows.find(row=>row.label==='名称')?.value,'示例站点',JSON.stringify(saved.rows));
  const groupIndex=saved.rows.findIndex(row=>row.label==='匹配规则');
  assert.equal(saved.rows[groupIndex]?.kind,'group',JSON.stringify(saved.rows));
  assert.deepEqual(saved.rows[groupIndex].fields.map(field=>field.value),['severity','P[0-2]']);
  assert.equal(saved.rows[groupIndex].confirmed,false);
  const group=panel.locator('.data-row').nth(groupIndex);
  assert.equal(await group.locator('.group-fields textarea').count(),2);
  await group.locator('[aria-label^="参与填写"]').check();
  await group.getByRole('button',{name:'确认当前值',exact:true}).click();
  await panel.screenshot({path:path.join(root,'test-artifacts/structured-panel.png'),fullPage:true});
  await panel.reload();
  await panel.waitForFunction(()=>!document.getElementById('choose').disabled);
  assert.equal(await panel.locator('.data-row').nth(groupIndex).locator('[aria-label^="参与填写"]').isChecked(),true,'Typed groups survive storage restore');
  assert.equal(await panel.locator('#fill').isVisible(),true);
  await target.bringToFront();await panel.evaluate(()=>document.getElementById('fill').click());
  await panel.waitForFunction(()=>document.getElementById('summary').textContent==='3 项已写入',null,{timeout:20000});
  assert.equal(await target.locator('#name').inputValue(),'示例站点');
  assert.equal(await target.locator('#priority').inputValue(),'20');
  assert.equal(await target.locator('#key').inputValue(),'severity');
  assert.equal(await target.locator('#value').inputValue(),'P[0-2]');
  assert.equal(await target.locator('#regex').isChecked(),false,'An image without state evidence must not modify state');
  assert.equal(await target.evaluate(()=>!!globalThis.submitted),false);
  await target.screenshot({path:path.join(root,'test-artifacts/structured-filled.png')});
  await panel.setViewportSize({width:300,height:780});
  assert.equal(await panel.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await panel.screenshot({path:path.join(root,'test-artifacts/structured-narrow.png'),fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
  await panel.evaluate(async index=>{
    const {savedCapture}=await chrome.storage.local.get('savedCapture');
    savedCapture.rows[index].fields.push({label:'正则表达式',kind:'checkbox',value:'',checked:true,confirmed:true});
    await chrome.runtime.sendMessage({type:'HISTORY',action:{type:'update',id:savedCapture.id,revision:savedCapture.revision,patch:{rows:savedCapture.rows}}});
  },groupIndex);
  await panel.reload();
  const state=panel.locator('.group-field input[type="checkbox"]');
  await state.waitFor({state:'attached'});
  assert.equal(await state.isChecked(),true);
  assert.equal(await state.evaluate(node=>{const label=node.previousElementSibling.getBoundingClientRect(),control=node.getBoundingClientRect(),row=node.parentElement.getBoundingClientRect();return control.left>=label.right && control.right<=row.right && control.top<row.bottom && control.bottom>row.top;}),true,'State control remains beside its label within the group row');
  assert.equal(await panel.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await panel.screenshot({path:path.join(root,'test-artifacts/structured-state-panel.png'),fullPage:true});
  console.log('PASS: external image without source DOM → offline OCR → editable typed group → review → storage restore → one-click reordered target; exact values, state preserved, no submit, narrow layout');
} finally {await context?.close();await new Promise(resolve=>server.close(resolve));}
