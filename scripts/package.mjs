import { cp, copyFile, mkdir, readdir, readFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const output = path.resolve(process.argv[2] || path.join(root, '../../outputs'));
const extension = path.join(output, '截图填表插件');
const source = path.join(output, '截图填表源码');
await mkdir(output, { recursive: true });
await mkdir(extension, { recursive: true });
for (const entry of await readdir(path.join(root, 'dist'))) await cp(path.join(root, 'dist', entry), path.join(extension, entry), { recursive: true });
await mkdir(source, { recursive: true });
for (const entry of ['src', 'scripts', 'tests', 'docs', 'licenses', 'package.json', 'package-lock.json', 'model-sha256.json', '.gitignore', 'README.md', 'AGENTS.md']) await cp(path.join(root, entry), path.join(source, entry), { recursive: true });
await mkdir(path.join(source, '.model-cache'), { recursive: true });
for (const lang of ['eng', 'chi_sim']) await copyFile(path.join(root, '.model-cache', `${lang}.traineddata.gz`), path.join(source, '.model-cache', `${lang}.traineddata.gz`));
await copyFile(path.join(root, 'README.md'), path.join(output, '安装使用说明.md'));
await copyFile(path.join(root, 'src/demo.html'), path.join(output, '测试表单.html'));
