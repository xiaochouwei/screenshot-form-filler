await copyFile(path.join(root,'docs/verification-0.9.1.md'),path.join(output,'0.9.1-侧栏开关与残留清理验证.md'));
await copyFile(path.join(root,'test-artifacts/regression-0.9.1.log'),path.join(output,'0.9.1-完整回归日志.txt'));
